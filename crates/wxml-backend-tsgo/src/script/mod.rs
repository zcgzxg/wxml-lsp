/// Optional resolver for non-relative module specifiers.
///
/// Relative specifiers are always resolved inside the snapshot first. The LSP
/// adapter supplies this trait for `baseUrl`/`paths` aliases; returning a path
/// that is not part of the request snapshot is treated as unresolved.
pub trait ModuleResolver {
    /// Resolves `specifier` from `from_path` to a project-relative file path.
    fn resolve(&self, specifier: &str, from_path: &str) -> Option<String>;
}

/// One script-analysis request over an immutable input snapshot.
#[derive(Clone, Copy)]
pub struct ScriptRequest<'a> {
    /// Project snapshot.
    pub input: &'a AnalysisInput,
    /// Project-relative script path.
    pub path: &'a str,
    /// Requested registration root.
    pub kind: RegistrationKind,
    /// Optional non-relative module resolver.
    pub resolver: Option<&'a dyn ModuleResolver>,
}

impl std::fmt::Debug for ScriptRequest<'_> {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("ScriptRequest")
            .field("path", &self.path)
            .field("kind", &self.kind)
            .field("resolver", &self.resolver.is_some())
            .finish_non_exhaustive()
    }
}

impl<'a> ScriptRequest<'a> {
    /// Creates a request with no module alias resolver.
    #[must_use]
    pub const fn new(input: &'a AnalysisInput, path: &'a str, kind: RegistrationKind) -> Self {
        Self {
            input,
            path,
            kind,
            resolver: None,
        }
    }

    /// Adds a module alias resolver.
    #[must_use]
    pub const fn with_resolver(mut self, resolver: &'a dyn ModuleResolver) -> Self {
        self.resolver = Some(resolver);
        self
    }
}

/// Registration selection for one requested root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RegistrationSelection {
    /// Requested root.
    pub requested: RegistrationKind,
    /// Selected literal registration.
    pub selected: Option<RegistrationFact>,
    /// Literal registrations considered by the request, including the
    /// Page→Component fallback and alias calls. Ambiguity is computed only
    /// among candidates of the selected registration kind.
    pub candidates: Vec<RegistrationFact>,
    /// Rejected registration-shaped calls.
    pub unsupported: Vec<UnsupportedRegistration>,
    /// False when multiple top-level same-kind candidates (or multiple
    /// same-kind candidates and no top-level one), a non-top-level selection
    /// or rejected calls make the owner ambiguous.
    pub complete: bool,
}

/// Complete script facts for one registration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScriptAnalysis {
    /// Project-relative script path.
    pub path: String,
    /// Overall support state.
    pub status: CapabilityStatus,
    /// Degradation reasons in stable order.
    pub reasons: Vec<String>,
    /// Non-degrading notes.
    pub notes: Vec<String>,
    /// Registration selection.
    pub registration: RegistrationSelection,
    /// Behavior graph facts.
    pub behavior: BehaviorResolution,
    /// Data overlay.
    pub data: DataOverlay,
    /// Property overlay.
    pub properties: PropertyOverlay,
    /// Method table used for event resolution.
    pub methods: MethodTable,
    /// Stable symbols with rename safety.
    pub symbols: Vec<ScriptSymbol>,
}

impl ScriptAnalysis {
    /// Resolves event bindings against the method table.
    #[must_use]
    pub fn resolve_events(&self, events: &[EventBinding]) -> EventCollection {
        events::resolve_events(&self.methods, events)
    }

    /// Looks a symbol up by exact name and kind.
    #[must_use]
    pub fn symbol(&self, name: &str, kind: SymbolKind) -> Option<&ScriptSymbol> {
        self.symbols
            .iter()
            .find(|symbol| symbol.name == name && symbol.kind == kind)
    }
}

/// Script-analysis failure for an unrecoverable request.
#[derive(Debug, Error)]
pub enum ScriptError {
    /// The requested script is not part of the input snapshot.
    #[error("script is not part of the input snapshot: {path}")]
    MissingFile {
        /// Requested path.
        path: String,
    },
    /// The script text cannot be scanned within the slice's grammar.
    #[error("invalid script input ({feature}): {reason}")]
    Invalid {
        /// Feature marker.
        feature: &'static str,
        /// Bounded reason.
        reason: String,
    },
    /// The construct is valid but deliberately unsupported here.
    #[error("unsupported script construct ({feature}): {reason}")]
    Unsupported {
        /// Feature marker.
        feature: &'static str,
        /// Bounded reason.
        reason: String,
    },
}

/// Analyzes one script registration and its static semantic graph.
#[allow(clippy::too_many_lines)] // one orchestration pass over registration/behavior/overlays/events
pub fn analyze_script(request: &ScriptRequest<'_>) -> Result<ScriptAnalysis, ScriptError> {
    let snapshot = Snapshot::new(request.input, request.resolver);
    let file = snapshot
        .file(request.path)
        .ok_or_else(|| ScriptError::MissingFile {
            path: request.path.to_owned(),
        })?;
    let scan = registration::scan(file)?;
    let selected = registration::select(file, &scan, request.kind)?;

    let selected_fact = selected.as_ref().map(|selected| selected.fact.clone());
    let candidates = scan
        .registrations
        .iter()
        .filter(|candidate| match request.kind {
            RegistrationKind::Page => {
                matches!(
                    candidate.kind,
                    RegistrationKind::Page | RegistrationKind::Component
                )
            }
            RegistrationKind::Component | RegistrationKind::Behavior => {
                candidate.kind == request.kind
            }
        })
        .cloned()
        .collect::<Vec<_>>();
    let selected_kind = selected
        .as_ref()
        .map_or(request.kind, |selected| selected.fact.kind);
    // A Page and a Component in one file are a normal fallback pair, not two
    // Page registrations. Count ambiguity only within the selected kind.
    let integrity = selected
        .as_ref()
        .map(|selected| registration::selection_integrity(&scan, &selected.fact));
    let ambiguous = integrity.is_some_and(|integrity| integrity.ambiguous);
    let mut reasons = Vec::new();
    let mut notes = Vec::new();
    if ambiguous {
        reasons.push(format!(
            "multiple {} registrations; the preferred candidate is selected",
            selected_kind.registrar()
        ));
    }
    if integrity.is_some_and(|integrity| integrity.not_top_level) {
        reasons.push(format!(
            "the selected {} registration is not top-level",
            selected_kind.registrar()
        ));
    }
    if scan
        .unsupported
        .iter()
        .any(|candidate| candidate.kind == selected_kind)
    {
        reasons.push("a registration-shaped call is not a literal object".to_owned());
    }

    let Some(registration) = selected.as_ref() else {
        return Ok(missing_registration(
            file,
            request.kind,
            &scan,
            candidates,
            reasons,
        ));
    };

    let behavior = behavior::resolve(&snapshot, file, registration);
    let (data, properties) = properties::build(&snapshot, file, registration, &behavior);
    let methods = events::build_table(
        file,
        &scan,
        registration,
        &behavior.methods,
        behavior.methods_incomplete || !behavior.status.is_supported(),
    );
    push_status_reason(&mut reasons, &behavior.status, "behavior");
    push_status_reason(&mut reasons, &data.status, "data");
    push_status_reason(&mut reasons, &properties.status, "properties");
    push_status_reason(&mut reasons, &methods.status, "events");
    if let Some(unsupported) = scan
        .unsupported
        .iter()
        .find(|candidate| candidate.kind == request.kind)
    {
        notes.push(format!(
            "rejected {} call: {}",
            unsupported.kind.registrar(),
            unsupported.reason
        ));
    }

    let symbols = build_symbols(
        file,
        registration,
        &behavior,
        &data,
        &properties,
        &methods,
        ambiguous,
    );
    let complete = integrity.is_some_and(registration::SelectionIntegrity::is_complete)
        && scan
            .unsupported
            .iter()
            .all(|candidate| candidate.kind != selected_kind);
    let unsupported = scan.unsupported;
    let status = combine_status(&reasons);
    Ok(ScriptAnalysis {
        path: file.path().to_owned(),
        status,
        reasons,
        notes,
        registration: RegistrationSelection {
            requested: request.kind,
            selected: selected_fact,
            candidates,
            unsupported,
            complete,
        },
        behavior,
        data,
        properties,
        methods,
        symbols,
    })
}

fn missing_registration(
    file: &SourceFile,
    kind: RegistrationKind,
    scan: &registration::RegistrationScan,
    candidates: Vec<RegistrationFact>,
    mut reasons: Vec<String>,
) -> ScriptAnalysis {
    if kind == RegistrationKind::Page && candidates.is_empty() {
        // Keep the same reason text the TS owner table uses for dynamic calls.
        reasons.push("no local Page registration".to_owned());
    } else {
        reasons.push(format!(
            "no local {} registration with an object literal argument",
            kind.registrar()
        ));
    }
    for rejected in &scan.unsupported {
        if rejected.kind == kind {
            reasons.push(format!(
                "registration is not a literal object ({})",
                rejected.reason
            ));
        }
    }
    let unsupported = scan.unsupported.clone();
    let candidates_empty = candidates.is_empty();
    let owner = match kind {
        RegistrationKind::Page => "page",
        RegistrationKind::Component => "component",
        RegistrationKind::Behavior => "behavior",
    };
    let reason_text = reasons.join("; ");
    let status = if candidates_empty && unsupported.is_empty() {
        CapabilityStatus::Unsupported {
            reason: reason_text.clone(),
        }
    } else {
        CapabilityStatus::Partial {
            reason: reason_text.clone(),
        }
    };
    ScriptAnalysis {
        path: file.path().to_owned(),
        status,
        reasons: reasons.clone(),
        notes: Vec::new(),
        registration: RegistrationSelection {
            requested: kind,
            selected: None,
            candidates,
            unsupported,
            complete: false,
        },
        behavior: BehaviorResolution::empty(),
        data: DataOverlay {
            status: CapabilityStatus::Unsupported {
                reason: reason_text.clone(),
            },
            root: DataRootKind::Unsupported,
            fields: Vec::new(),
            complete: false,
            problems: reasons.clone(),
        },
        properties: PropertyOverlay {
            status: CapabilityStatus::Unsupported {
                reason: reason_text.clone(),
            },
            properties: Vec::new(),
            complete: false,
            problems: reasons.clone(),
        },
        methods: MethodTable {
            status: CapabilityStatus::Partial {
                reason: reason_text,
            },
            owner,
            methods: Vec::new(),
            opaque: Vec::new(),
            problems: reasons,
        },
        symbols: Vec::new(),
    }
}

fn push_status_reason(reasons: &mut Vec<String>, status: &CapabilityStatus, area: &str) {
    match status {
        CapabilityStatus::Supported => {}
        CapabilityStatus::Partial { reason }
        | CapabilityStatus::Unsupported { reason }
        | CapabilityStatus::Disabled { reason }
        | CapabilityStatus::Unavailable { reason } => {
            reasons.push(format!("{area}: {reason}"));
        }
        CapabilityStatus::Unknown { reason } => reasons.push(reason.as_ref().map_or_else(
            || format!("{area}: capability is unknown"),
            |reason| format!("{area}: {reason}"),
        )),
        _ => reasons.push(format!("{area}: script capability is degraded")),
    }
}

fn combine_status(reasons: &[String]) -> CapabilityStatus {
    if reasons.is_empty() {
        CapabilityStatus::Supported
    } else {
        CapabilityStatus::Partial {
            reason: reasons.join("; "),
        }
    }
}

#[allow(clippy::too_many_lines)] // one symbol assembly pass
fn build_symbols(
    file: &SourceFile,
    registration: &ParsedRegistration,
    behavior: &BehaviorResolution,
    data: &DataOverlay,
    properties: &PropertyOverlay,
    methods: &MethodTable,
    ambiguous: bool,
) -> Vec<ScriptSymbol> {
    let owner = match registration.fact.kind {
        RegistrationKind::Page => SymbolOwner::Page,
        RegistrationKind::Component => SymbolOwner::Component,
        RegistrationKind::Behavior => SymbolOwner::Behavior,
    };
    let mut symbols = Vec::new();
    let utf16 = symbols::Utf16Index::new(file.text());
    let mut registration_safety = RenameSafety::safe();
    registration_safety.block(RenameBlock::RegistrationName);
    if ambiguous {
        registration_safety.block(RenameBlock::AmbiguousRegistration);
    }
    if let Ok(range) = ScriptRange::from_index(&utf16, file.text(), registration.fact.name_range) {
        symbols.push(ScriptSymbol {
            owner,
            path: file.path().to_owned(),
            name: registration
                .fact
                .alias
                .clone()
                .unwrap_or_else(|| registration.fact.kind.registrar().to_owned()),
            kind: SymbolKind::Registration,
            range,
            origin: DefinitionOrigin::Original,
            safety: registration_safety,
            documentation: String::new(),
            type_text: None,
            default_text: None,
        });
    }

    for field in &data.fields {
        let origin = origin_for(file, &field.path, behavior);
        let mut safety = RenameSafety::safe();
        if ambiguous {
            safety.block(RenameBlock::AmbiguousRegistration);
        }
        if !field.exact || !data.status.is_supported() {
            safety.block(RenameBlock::IncompleteEvidence);
        }
        if field.path != file.path() {
            safety.block(RenameBlock::CrossFileEvidence);
        } else if is_quoted(file.text(), field.range) {
            safety.block(RenameBlock::QuotedKey);
        }
        symbols.push(ScriptSymbol {
            owner,
            path: field.path.clone(),
            name: field.name.clone(),
            kind: SymbolKind::Data,
            range: field.range,
            origin,
            safety,
            documentation: field.documentation.clone(),
            type_text: Some(field.type_text.clone()),
            default_text: None,
        });
    }

    for property in &properties.properties {
        let origin = origin_for(file, &property.path, behavior);
        let mut safety = RenameSafety::safe();
        if ambiguous {
            safety.block(RenameBlock::AmbiguousRegistration);
        }
        if !properties.status.is_supported() {
            safety.block(RenameBlock::IncompleteEvidence);
        }
        if property.path != file.path() {
            safety.block(RenameBlock::CrossFileEvidence);
        } else if is_quoted(file.text(), property.range) {
            safety.block(RenameBlock::QuotedKey);
        }
        symbols.push(ScriptSymbol {
            owner,
            path: property.path.clone(),
            name: property.name.clone(),
            kind: SymbolKind::Property,
            range: property.range,
            origin,
            safety,
            documentation: property.documentation.clone(),
            type_text: Some(property.type_text.clone()),
            default_text: property.default_text.clone(),
        });
    }

    for method in &methods.methods {
        let origin = origin_for(file, &method.path, behavior);
        let mut safety = RenameSafety::safe();
        if ambiguous {
            safety.block(RenameBlock::AmbiguousRegistration);
        }
        if !methods.status.is_supported() {
            safety.block(RenameBlock::IncompleteEvidence);
        }
        if method.path != file.path() {
            safety.block(RenameBlock::CrossFileEvidence);
        } else if is_quoted(file.text(), method.range) {
            safety.block(RenameBlock::QuotedKey);
        }
        let kind = if method.path == file.path() {
            SymbolKind::Method
        } else {
            SymbolKind::BehaviorMethod
        };
        symbols.push(ScriptSymbol {
            owner,
            path: method.path.clone(),
            name: method.name.clone(),
            kind,
            range: method.range,
            origin,
            safety,
            documentation: method.documentation.clone(),
            type_text: None,
            default_text: None,
        });
    }
    symbols
}

fn origin_for(file: &SourceFile, path: &str, behavior: &BehaviorResolution) -> DefinitionOrigin {
    if path == file.path() {
        return DefinitionOrigin::Original;
    }
    let alias = behavior
        .units
        .iter()
        .find(|unit| unit.path == path)
        .and_then(|unit| unit.alias.clone());
    DefinitionOrigin::ImportedBehavior {
        path: path.to_owned(),
        alias,
    }
}

fn is_quoted(text: &str, range: ScriptRange) -> bool {
    range
        .text(text)
        .is_some_and(|token| token.starts_with('"') || token.starts_with('\''))
}
