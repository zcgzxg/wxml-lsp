//! Rust-side mini-program script semantics.
//!
//! This is the first vertical slice of the `P4-B` script package. It reads one
//! immutable [`AnalysisInput`] snapshot and derives the facts the native query
//! layer needs before it can compose hover, definition and diagnostics:
//!
//! - `Page`/`Component`/`Behavior` registrations, including static registrar
//!   aliases and multiple-call ambiguity ([`registration`]);
//! - the static Behavior graph with imports, re-export aliases, nested
//!   behaviors, spreads and cycle detection ([`behavior`]);
//! - `data`/`properties` overlays with own/behavior precedence, `optionalTypes`,
//!   defaults and `JSDoc` ([`properties`]);
//! - script-side event handler registration and resolution for all
//!   `bind*`/`catch*`/`capture-*` forms ([`events`]);
//! - stable symbols with UTF-8/UTF-16 ranges and conservative rename safety
//!   ([`symbols`]);
//! - reusable symbol-channel facts for data paths, references, `setData`
//!   occurrences and missing-handler insertions ([`symbol_facts`]).
//!
//! # Evidence boundary
//!
//! Everything here is syntactic. No native `tsgo` session, TypeScript checker,
//! Node process or file-system read is involved. Type texts are the narrow
//! literals this layer can prove; anything else is `any` with
//! `exact = false`, and the owning status becomes `Partial`. The following
//! therefore remain BLOCKED for the native query slices:
//!
//! - assignability diagnostics (for example component property `type`
//!   mismatch), hover type quality and `JSDoc` visibility from the checker;
//! - `this.data`/`this.properties` instance types generated by the in-place
//!   shadow and their native mappings;
//! - `typeRoots` interaction with pinned mini-program declarations;
//! - official metadata links (the existing `wxml-lsp` metadata layer owns
//!   those; this crate only preserves the `JSDoc` text it is given);
//! - cross-file rename/references proof. Symbols imported from a behavior file
//!   are marked unsafe for rename here.
//!
//! # Paths and units
//!
//! Paths are project-relative, `/`-separated and validated by [`crate::input`].
//! Ranges keep both the exact UTF-8 bytes from the shadow layer and the UTF-16
//! code units required by LSP/native APIs. Text is never normalized.

