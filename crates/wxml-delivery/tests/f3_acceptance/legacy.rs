//! F3-08: a schema v1 legacy package is never activated by native rollback.
//! F3-09: legacy -> native migration success, pre-activation failure and
//! post-switch interruption; the old tree stays byte-identical.
//! F3-15: legacy environment variables and entry points remain inert, and
//! `wxml-lsp-install env` prints only `WXML_LSP_BIN`.

use std::fs;

use wxml_delivery::error::DeliveryError;
use wxml_delivery::manifest::set_mode;
use wxml_delivery::native_install::FailPoint;
use wxml_delivery::state::Journal;

use crate::support::{
    LEGACY_VERSION, TestDir, Tripwires, VERSION_N1, VERSION_N2, active_version, assert_contains,
    assert_failure, assert_journal_empty, assert_legacy_current, assert_marker_absent,
    assert_state, assert_success, assert_tmp_empty, build_legacy_release, clear_marker, combined,
    evidence, fixture, install_legacy, install_n1, install_with_failpoint, installed_fingerprint,
    installed_versions, installer_bin, legacy_fingerprint, mutate_release, open_root, private_root,
    remove_typings, run_installer, run_installer_env, shared_channel, skip, stage_release_tree,
    state_bytes, stdout, upgrade_n2, workspace,
};
use wxml_delivery::verify_v2::collect_tree;

#[test]
#[ignore = "requires pinned real assets; run with --ignored"]
#[allow(clippy::too_many_lines)]
fn f3_08_09_15_legacy_migration_inert_env_and_v1_rollback() {
    let Some(channel) = shared_channel("f3_08_09_15_legacy") else {
        skip(
            "F3-08/F3-09/F3-15",
            "pinned real assets are absent; set TSGO_NATIVE_TARBALL/TSGO_TYPINGS_TARBALL or WXML_REQUIRE_REAL_ENGINE=1",
        );
        return;
    };
    let base = TestDir::new("f3-legacy");
    let (work, _home, _tmp) = workspace(&base);
    let tripwires = Tripwires::install(base.path());
    let install_bin = installer_bin();
    let marker = base.path().join("LEGACY_ENTRY_EXECUTED");
    let legacy_release = build_legacy_release(&base, &marker);
    fixture(
        "F3-08/F3-09/F3-15",
        "the schema v1 package is generated by the production v1 packager and the pre/post-switch \
         interruption journals are test-injected; the native target is the real production release",
    );

    let make_legacy_root = |name: &str| {
        let root = private_root(&base, name);
        let install = install_legacy(&install_bin, &legacy_release, &root, &tripwires, &work);
        assert_success(&install, "legacy v1 fixture install");
        clear_marker(&marker);
        assert_legacy_current(&root);
        root
    };

    // F3-15: legacy read-only commands must not execute the old entry point and
    // `env` must print exactly one export.
    let legacy_root = make_legacy_root("legacy-readonly-root");
    let root_text = legacy_root.to_str().expect("UTF-8 root");
    for (command, expected) in [
        ("current", "schema: 1 (legacy, read-only; nothing executed)"),
        ("list", "(legacy, read-only)"),
        ("verify", "nothing was executed"),
    ] {
        let output = run_installer(
            &install_bin,
            &[command, "--root", root_text],
            &tripwires,
            &work,
            &format!("legacy {command}"),
        );
        assert_success(&output, &format!("legacy {command}"));
        assert_contains(&output, &[expected]);
        assert_marker_absent(&marker);
        evidence(
            "F3-15",
            "PASS",
            format!(
                "legacy `{command}` stayed read-only; legacy entry point was not executed; \
                 detail={}",
                combined(&output).trim().replace('\n', " | ")
            ),
        );
    }
    let env = run_installer(
        &install_bin,
        &["env", "--root", root_text],
        &tripwires,
        &work,
        "legacy env",
    );
    assert_success(&env, "legacy env");
    let env_text = stdout(&env);
    let lines: Vec<&str> = env_text.lines().collect();
    assert_eq!(
        lines.len(),
        1,
        "env must print exactly one export: {lines:?}"
    );
    assert!(lines[0].starts_with("export WXML_LSP_BIN="), "{lines:?}");
    assert!(
        !stdout(&env).contains("WXML_TYPE_BACKEND")
            && !stdout(&env).contains("WXML_BACKEND_DIR")
            && !stdout(&env).contains("WXML_NODE"),
        "legacy env leaked: {}",
        stdout(&env)
    );
    assert_marker_absent(&marker);
    evidence(
        "F3-15",
        "PASS",
        "legacy `env` printed only `export WXML_LSP_BIN=...`; no legacy backend variables and no \
         legacy process execution",
    );

    // F3-09 success: migrate the legacy fixture to the real native package.
    let legacy_fp = legacy_fingerprint(&legacy_root, LEGACY_VERSION);
    let migrate = run_installer(
        &install_bin,
        &[
            "install",
            "--root",
            root_text,
            "--from-dir",
            channel.channel.to_str().expect("UTF-8 channel"),
            "--version",
            VERSION_N1,
            "--offline",
        ],
        &tripwires,
        &work,
        "legacy to native migration",
    );
    assert_success(&migrate, "legacy to native migration");
    assert_contains(&migrate, &["migrated to 0.1.0 (native)"]);
    assert_state(&legacy_root, VERSION_N1, None);
    assert_eq!(
        active_version(&open_root(&legacy_root)).as_deref(),
        Some(VERSION_N1)
    );
    assert_eq!(
        legacy_fingerprint(&legacy_root, LEGACY_VERSION),
        legacy_fp,
        "legacy tree changed during migration"
    );
    assert_marker_absent(&marker);
    evidence(
        "F3-09",
        "PASS",
        "legacy fixture migrated to real N1; state.previous=null; legacy tree byte-identical; \
         legacy entry point was not executed",
    );

    // F3-08: native rollback must refuse the schema v1 target.
    let root = open_root(&legacy_root);
    let state_before = state_bytes(&legacy_root);
    let n1_fingerprint = installed_fingerprint(&legacy_root, VERSION_N1);
    let rollback = run_installer(
        &install_bin,
        &[
            "rollback",
            "--root",
            root_text,
            "--to",
            LEGACY_VERSION,
            "--offline",
        ],
        &tripwires,
        &work,
        "rollback to legacy v1",
    );
    assert_failure(&rollback, "rollback to legacy v1");
    assert_contains(&rollback, &["legacy node package"]);
    assert_eq!(
        active_version(&root).as_deref(),
        Some(VERSION_N1),
        "rollback activated the legacy package"
    );
    assert_eq!(state_bytes(&legacy_root), state_before);
    assert_eq!(
        installed_fingerprint(&legacy_root, VERSION_N1),
        n1_fingerprint
    );
    assert_eq!(legacy_fingerprint(&legacy_root, LEGACY_VERSION), legacy_fp);
    assert_marker_absent(&marker);
    evidence(
        "F3-08",
        "PASS",
        "native rollback --to legacy v1 was rejected without touching current/state/or either tree",
    );

    // F3-15: the installed native package contains no legacy entry point and
    // ignores legacy env variables.
    let contents = collect_tree(&legacy_root.join("current")).expect("collect installed tree");
    for path in &contents.files {
        let lower = path.to_ascii_lowercase();
        assert!(
            !lower.contains("wxml-type-backend"),
            "native tree contains the legacy backend entry: {path}"
        );
        let extension = lower.rsplit_once('.').map(|(_, extension)| extension);
        assert!(
            !matches!(extension, Some("js" | "cjs" | "mjs")),
            "native tree contains a legacy JavaScript payload: {path}"
        );
    }
    let native_env = run_installer(
        &install_bin,
        &["env", "--root", root_text],
        &tripwires,
        &work,
        "native env with legacy variables",
    );
    assert_success(&native_env, "native env");
    let native_env_text = stdout(&native_env);
    let lines: Vec<&str> = native_env_text.lines().collect();
    assert_eq!(lines.len(), 1, "{lines:?}");
    assert!(lines[0].starts_with("export WXML_LSP_BIN="), "{lines:?}");
    assert_marker_absent(&marker);
    let mut version_command =
        crate::support::clean_command(&legacy_root.join("current/bin/wxml-lsp"), &tripwires, &work);
    version_command.arg("--version");
    let version = crate::support::run_with_deadline(
        &mut version_command,
        std::time::Duration::from_secs(30),
        "installed binary --version with legacy env",
    );
    assert_success(&version, "installed binary --version");
    assert!(
        stdout(&version).contains("wxml-lsp 0.1.0"),
        "{}",
        stdout(&version)
    );
    assert_marker_absent(&marker);
    evidence(
        "F3-15",
        "PASS",
        "native tree has no wxml-type-backend/JavaScript entry; native env printed only \
         WXML_LSP_BIN; the packaged binary ignored legacy env variables",
    );

    // F3-09 failure: a real N1 package missing typings must not disturb legacy.
    let failure_root = make_legacy_root("legacy-failure-root");
    let failure_fingerprint = legacy_fingerprint(&failure_root, LEGACY_VERSION);
    let missing_typings = mutate_release(
        base.path(),
        &channel.n1,
        "n1-missing-typings-for-migration",
        remove_typings,
    );
    let failed = run_installer(
        &install_bin,
        &[
            "install",
            "--root",
            failure_root.to_str().expect("UTF-8 root"),
            "--from-dir",
            missing_typings.release_dir.to_str().expect("UTF-8 variant"),
            "--version",
            VERSION_N1,
            "--offline",
        ],
        &tripwires,
        &work,
        "failed legacy migration",
    );
    assert_failure(&failed, "failed legacy migration");
    let failure_handle = open_root(&failure_root);
    assert_eq!(
        active_version(&failure_handle).as_deref(),
        Some(LEGACY_VERSION)
    );
    assert_eq!(state_bytes(&failure_root), None);
    assert_eq!(
        installed_versions(&failure_handle),
        vec![LEGACY_VERSION.to_owned()]
    );
    assert_eq!(
        legacy_fingerprint(&failure_root, LEGACY_VERSION),
        failure_fingerprint
    );
    assert_tmp_empty(&failure_handle);
    assert_journal_empty(&failure_handle);
    assert_marker_absent(&marker);
    evidence(
        "F3-09",
        "PASS",
        "real package missing typings rejected before activation; legacy current/tree/state \
         unchanged",
    );

    // F3-09 interruption before switch: the target is committed, never
    // auto-activated, and an explicit retry performs the migration.
    let interrupted_root = make_legacy_root("legacy-interrupted-root");
    let interrupted_fingerprint = legacy_fingerprint(&interrupted_root, LEGACY_VERSION);
    let interrupted_handle = open_root(&interrupted_root);
    let staged = stage_release_tree(&interrupted_handle, &channel.n1);
    let error = install_with_failpoint(
        &interrupted_handle,
        &staged,
        VERSION_N1,
        FailPoint::AfterRename,
    )
    .unwrap_err();
    assert!(matches!(error, DeliveryError::Runtime(_)), "{error:?}");
    assert_eq!(
        active_version(&interrupted_handle).as_deref(),
        Some(LEGACY_VERSION)
    );
    assert_eq!(state_bytes(&interrupted_root), None);
    let journals = Journal::list(&interrupted_handle).expect("list journals");
    assert_eq!(journals.len(), 1, "{journals:?}");
    assert_eq!(
        journals[0].state,
        wxml_delivery::state::TransactionState::Committed
    );
    assert_eq!(journals[0].previous, None, "legacy must never be previous");
    let recover = run_installer(
        &install_bin,
        &[
            "recover",
            "--root",
            interrupted_root.to_str().expect("UTF-8 root"),
        ],
        &tripwires,
        &work,
        "recover legacy committed migration",
    );
    assert_success(&recover, "recover legacy committed migration");
    assert_contains(&recover, &["not auto-activated"]);
    assert_eq!(
        active_version(&open_root(&interrupted_root)).as_deref(),
        Some(LEGACY_VERSION)
    );
    assert_eq!(
        legacy_fingerprint(&interrupted_root, LEGACY_VERSION),
        interrupted_fingerprint
    );
    let retry = run_installer(
        &install_bin,
        &[
            "install",
            "--root",
            interrupted_root.to_str().expect("UTF-8 root"),
            "--from-dir",
            channel.channel.to_str().expect("UTF-8 channel"),
            "--version",
            VERSION_N1,
            "--offline",
        ],
        &tripwires,
        &work,
        "explicit legacy migration retry",
    );
    assert_success(&retry, "explicit legacy migration retry");
    assert_contains(&retry, &["migrated to 0.1.0 (native)"]);
    assert_eq!(
        active_version(&open_root(&interrupted_root)).as_deref(),
        Some(VERSION_N1)
    );
    assert_eq!(
        legacy_fingerprint(&interrupted_root, LEGACY_VERSION),
        interrupted_fingerprint
    );
    assert_journal_empty(&open_root(&interrupted_root));
    assert_marker_absent(&marker);
    evidence(
        "F3-09",
        "PASS",
        "interruption after rename left legacy current and tree unchanged; recovery did not \
         auto-activate; explicit retry migrated to N1",
    );

    // F3-09 interruption after switch: the verified native target rolls
    // forward; the legacy tree stays byte-identical and is never restored.
    let switched_root = make_legacy_root("legacy-switched-root");
    let switched_fingerprint = legacy_fingerprint(&switched_root, LEGACY_VERSION);
    let switched_handle = open_root(&switched_root);
    let staged = stage_release_tree(&switched_handle, &channel.n1);
    let error = install_with_failpoint(
        &switched_handle,
        &staged,
        VERSION_N1,
        FailPoint::AfterSwitch,
    )
    .unwrap_err();
    let DeliveryError::SwitchedButNotDurable {
        version,
        previous,
        state_reconciled,
        ..
    } = error
    else {
        panic!("expected typed post-switch migration state, got {error:?}");
    };
    assert_eq!(version, VERSION_N1);
    assert_eq!(previous, None, "legacy is never a native previous");
    assert!(
        state_reconciled,
        "the verified native target must roll forward"
    );
    assert_eq!(
        active_version(&open_root(&switched_root)).as_deref(),
        Some(VERSION_N1)
    );
    assert_state(&switched_root, VERSION_N1, None);
    assert_eq!(
        legacy_fingerprint(&switched_root, LEGACY_VERSION),
        switched_fingerprint
    );
    assert!(
        fs::read_dir(switched_root.join("versions"))
            .expect("read versions")
            .any(|entry| entry.expect("entry").file_name().to_string_lossy() == LEGACY_VERSION)
    );
    assert_marker_absent(&marker);
    evidence(
        "F3-09",
        "PASS",
        "interruption after switch rolled the verified native target forward; the legacy tree \
         stayed byte-identical and was never reactivated",
    );

    evidence(
        "F3-09",
        "BLOCKED",
        "SIGKILL at an exact pre/post-switch instruction is not a public production seam; this \
         evidence uses the deterministic `InstallHooks` checkpoints",
    );
    tripwires.assert_not_executed();
    println!(
        "F3-08/F3-09/F3-15: legacy read-only/environment inertness, successful migration, \
         pre-activation failure, commit/recover and post-switch roll-forward all completed"
    );
}

#[test]
#[ignore = "requires pinned real assets; run with --ignored"]
#[allow(clippy::too_many_lines)]
fn f3_15_explicit_binary_precedence_for_install_upgrade_rollback() {
    let Some(channel) = shared_channel("f3_15_binary_precedence") else {
        skip(
            "F3-15",
            "pinned real assets are absent; set TSGO_NATIVE_TARBALL/TSGO_TYPINGS_TARBALL or WXML_REQUIRE_REAL_ENGINE=1",
        );
        return;
    };
    let base = TestDir::new("f3-15-precedence");
    let (work, _home, _tmp) = workspace(&base);
    let tripwires = Tripwires::install(base.path());
    let install_bin = installer_bin();
    let root_path = private_root(&base, "root");
    let root_text = root_path.to_str().expect("UTF-8 root");
    let channel_text = channel.channel.to_str().expect("UTF-8 channel");

    assert_success(
        &install_n1(&install_bin, channel, &root_path, &tripwires, &work),
        "F3-15 precedence baseline N1",
    );
    assert_success(
        &upgrade_n2(&install_bin, channel, &root_path, &tripwires, &work),
        "F3-15 precedence baseline N2",
    );
    assert_state(&root_path, VERSION_N2, Some(VERSION_N1));
    let state_before = state_bytes(&root_path);
    let n1_fingerprint = installed_fingerprint(&root_path, VERSION_N1);
    let n2_fingerprint = installed_fingerprint(&root_path, VERSION_N2);

    let explicit = base.path().join("explicit-lsp");
    fs::write(
        &explicit,
        b"#!/bin/sh\nif [ \"$1\" = \"--version\" ]; then printf 'wxml-lsp 9.9.9\\n'; fi\n",
    )
    .expect("write explicit binary");
    set_mode(&explicit, 0o755).expect("explicit binary mode");
    let explicit_text = explicit.to_str().expect("UTF-8 explicit binary");

    // A valid absolute WXML_LSP_BIN wins for all three mutating commands: each
    // one reports precedence and performs no install/upgrade/rollback.
    let cases: [(&str, Vec<&str>, &str); 3] = [
        (
            "install",
            vec![
                "install",
                "--root",
                root_text,
                "--from-dir",
                channel_text,
                "--version",
                VERSION_N1,
                "--offline",
            ],
            "No install or download was attempted",
        ),
        (
            "upgrade",
            vec![
                "upgrade",
                "--root",
                root_text,
                "--from-dir",
                channel_text,
                "--offline",
            ],
            "No upgrade or download was attempted",
        ),
        (
            "rollback",
            vec![
                "rollback",
                "--root",
                root_text,
                "--to",
                VERSION_N1,
                "--offline",
            ],
            "No rollback was attempted",
        ),
    ];
    for (command, args, expected) in &cases {
        let output = run_installer_env(
            &install_bin,
            args,
            &[("WXML_LSP_BIN", explicit_text)],
            &tripwires,
            &work,
            &format!("F3-15 valid WXML_LSP_BIN {command}"),
        );
        assert_success(&output, &format!("valid WXML_LSP_BIN {command}"));
        assert_contains(&output, &[*expected, "takes precedence"]);
        assert!(
            !stdout(&output).contains("(native)"),
            "{command} mutated the root despite WXML_LSP_BIN: {}",
            stdout(&output)
        );
        assert_eq!(state_bytes(&root_path), state_before, "{command}");
        assert_eq!(
            installed_fingerprint(&root_path, VERSION_N1),
            n1_fingerprint,
            "{command}"
        );
        assert_eq!(
            installed_fingerprint(&root_path, VERSION_N2),
            n2_fingerprint,
            "{command}"
        );
        evidence(
            "F3-15",
            "PASS",
            format!(
                "a valid absolute WXML_LSP_BIN made `{command}` report precedence without any \
                 install/upgrade/rollback; detail={}",
                combined(&output).trim().replace('\n', " | ")
            ),
        );
    }

    // An invalid WXML_LSP_BIN is a hard error for all three commands; it never
    // falls back to installing or switching.
    let missing = base.path().join("missing-lsp");
    let missing_text = missing.to_str().expect("UTF-8 missing binary");
    for (command, args, _) in &cases {
        let output = run_installer_env(
            &install_bin,
            args,
            &[("WXML_LSP_BIN", missing_text)],
            &tripwires,
            &work,
            &format!("F3-15 invalid WXML_LSP_BIN {command}"),
        );
        assert_failure(&output, &format!("invalid WXML_LSP_BIN {command}"));
        assert_contains(&output, &["WXML_LSP_BIN", "invalid"]);
        assert_eq!(state_bytes(&root_path), state_before, "{command}");
        assert_eq!(
            installed_fingerprint(&root_path, VERSION_N1),
            n1_fingerprint,
            "{command}"
        );
        assert_eq!(
            installed_fingerprint(&root_path, VERSION_N2),
            n2_fingerprint,
            "{command}"
        );
        evidence(
            "F3-15",
            "PASS",
            format!(
                "an invalid WXML_LSP_BIN made `{command}` fail hard with no fallback; detail={}",
                combined(&output).trim().replace('\n', " | ")
            ),
        );
    }

    tripwires.assert_not_executed();
    println!(
        "F3-15: valid WXML_LSP_BIN precedence and invalid-value hard errors were exercised for \
         install/upgrade/rollback over a real N1/N2 installation"
    );
}
